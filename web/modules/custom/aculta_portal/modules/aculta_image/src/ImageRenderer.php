<?php

declare(strict_types=1);

namespace Drupal\aculta_image;

use Drupal\Core\Cache\CacheableMetadata;
use Drupal\Core\Entity\EntityTypeManagerInterface;
use Drupal\image\ImageStyleInterface;
use Drupal\file\FileInterface;

/**
 * Renderização de imagem por finalidade (aculta_image, seção 3.1 do plano).
 *
 * Único ponto do site que entrega estilo de imagem ao Render API, à
 * configuração de campo e aos formulários. Quem
 * chama pede uma finalidade do catálogo; nunca um nome de estilo.
 */
final class ImageRenderer {

  public function __construct(
    private readonly ImageCatalog $catalog,
    private readonly EntityTypeManagerInterface $entityTypeManager,
  ) {}

  /**
   * Builds an image render array for the given purpose.
   *
   * Returns NULL when the purpose does not exist.
   */
  public function build(string $purpose, string $uri, string $alt, array $attributes = []): ?array {
    $style = $this->catalog->styleFor($purpose);
    if ($style === NULL) {
      return NULL;
    }
    $build = [
      '#theme' => 'image_style',
      '#style_name' => $style,
      '#uri' => $uri,
      '#alt' => $alt,
    ];
    if ($attributes !== []) {
      $build['#attributes'] = $attributes;
    }
    return $build;
  }

  /**
   * Builds markup for an image generated by a purpose-specific processor.
   */
  public function buildManagedImage(FileInterface $file, string $alt, array $attributes = []): ?array {
    if (!str_starts_with((string) $file->getMimeType(), 'image/')) {
      return NULL;
    }
    $build = [
      '#theme' => 'image',
      '#uri' => $file->getFileUri(),
      '#alt' => $alt,
    ];
    if ($attributes !== []) {
      $build['#attributes'] = $attributes;
    }
    CacheableMetadata::createFromObject($file)->applyTo($build);
    return $build;
  }

  /**
   * Retorna o estilo configurado para uma finalidade.
   */
  public function styleId(string $purpose): ?string {
    return $this->catalog->styleFor($purpose);
  }

  /**
   * Retorna a entidade de estilo de uma finalidade.
   *
   * Pode retornar NULL, por exemplo, ao descarregar derivados.
   */
  public function styleEntity(string $purpose): ?ImageStyleInterface {
    $style = $this->catalog->styleFor($purpose);
    if ($style === NULL) {
      return NULL;
    }
    $entity = $this->entityTypeManager->getStorage('image_style')->load($style);
    return $entity instanceof ImageStyleInterface ? $entity : NULL;
  }

  /**
   * Configuração de exibição de campo (`settings`) para a finalidade. */
  public function displaySettings(string $purpose): array {
    $style = $this->catalog->styleFor($purpose);
    return $style === NULL ? [] : ['image_style' => $style];
  }

}
